function signum_app_min_ios(array $app): string
{
    foreach ($app['versions'] ?? [] as $version) {
        if (!empty($version['is_latest']) && !empty($version['min_ios'])) {
            return (string)$version['min_ios'];
        }
    }

    foreach ($app['versions'] ?? [] as $version) {
        if (!empty($version['min_ios'])) {
            return (string)$version['min_ios'];
        }
    }

    return (string)($app['min_ios'] ?? '');
}

function signum_catalog_summary(array $app): array
{
    $summary = [
        'id' => $app['id'],
        'active' => $app['active'],
        'in_store' => $app['in_store'],
        'title' => $app['title'],
        'badge' => signum_resolve_badge($app),
        'version' => signum_app_version($app),
        'min_ios' => signum_app_min_ios($app),
        'color' => $app['color'],
        'icon_url' => $app['icon_url'],
        'app_store_url' => $app['app_store_url'] ?? null,
        'category' => $app['category'] ?? 'app',
        'aliases' => $app['aliases'] ?? [],
    ];
    if (!empty($app['activation']) && is_array($app['activation'])) {
        $summary['activation'] = $app['activation'];
    }
    // This function is a hard whitelist: a key not copied here never reaches
    // main.php, so a TestFlight card would render as an ordinary IPA install.
    if (!empty($app['testflight']) && is_array($app['testflight'])) {
        $summary['testflight'] = $app['testflight'];
    }
    return $summary;
}

function signum_enrich_app(array $app, ?string $iosVersion = null): array
{
    unset($app['bundle_id'], $app['app_store_id'], $app['min_ios'], $app['visible_for_versions'],
          $app['min_client_version']);
    $app['version'] = signum_app_version($app);
    $app['versions'] = signum_filter_versions_for_ios($app, $iosVersion);
    $app['badge'] = signum_resolve_badge($app);
    return $app;
}

function signum_enrich_version(array $app, array $version): array
{
    $version['title'] = (string)($version['title'] ?? $version['label'] ?? ($app['title'] ?? 'Приложение'));
    $version['description'] = (string)($version['description'] ?? '');
    $version['icon_url'] = (string)($version['icon_url'] ?? $app['icon_url'] ?? '');
    $version['badge'] = signum_resolve_badge([
        'badge' => $version['badge'] ?? null,
        'in_store' => $version['in_store'] ?? false,
    ]);
    // external_version_id is kept on purpose: Apple refuses the newest builds
    // of some pulled apps, and pinning a build it still serves is the only way
    // to restore them. No catalogue row used this key before, so nothing that
    // worked before changes.
    unset($version['externalVersionId'], $version['active']);
    return $version;
}

function signum_enrich_versions(array $app): array
{
    return array_values(array_map(
        static fn(array $version): array => signum_enrich_version($app, $version),
        $app['versions'] ?? []
    ));
}

function signum_filter_versions_for_ios(array $app, ?string $iosVersion): array
{
    $versions = signum_enrich_versions($app);
    if ($iosVersion === null || $iosVersion === '') {
        return $versions;
    }

    return array_values(array_filter(
        $versions,
        static fn(array $version): bool => signum_compare_builds($iosVersion, (string)($version['min_ios'] ?? '0')) >= 0
    ));
}

function signum_get_app_or_null(string $id, ?string $clientVersion = null): ?array
{
    $clientVersion = $clientVersion ?? trim((string)($_GET['vers'] ?? ''));
    $catalog = signum_catalog_apps();
    if ($id === '' || !isset($catalog[$id]) || !signum_app_visible_to_client($catalog[$id], $clientVersion)) {
        return null;
    }
    return $catalog[$id];
}

function signum_ota_releases(): array
{
    if (!is_file(SIGNUM_RELEASE_MANIFEST)) {
        return [];
    }
    $releases = require SIGNUM_RELEASE_MANIFEST;
    return is_array($releases) ? $releases : [];
}
function signum_ota_release(?string $platform = null): ?array
{
    $platform = signum_normalize_update_platform($platform ?? 'windows');
    $release = signum_ota_releases()[$platform] ?? null;
    if (!is_array($release)) {
        return null;
    }
    $version = trim((string)($release['version'] ?? ''));
    $downloadPath = trim((string)($release['download_url'] ?? ''));
    if ($version === '' || $downloadPath === '' || !str_starts_with($downloadPath, '/releases/')) {
        return null;
    }
    $sha256 = strtolower(trim((string)($release['sha256'] ?? '')));
    return [
        'platform' => $platform,
        'version' => $version,
        'build' => max(0, (int)($release['build'] ?? 0)),
        'mandatory' => !empty($release['mandatory']),
        'notes' => trim((string)($release['notes'] ?? '')),
        'download_url' => signum_base_url() . $downloadPath,
        'deb_download_url' => isset($release['deb_download_url']) && str_starts_with($release['deb_download_url'], '/releases/') ? signum_base_url() . $release['deb_download_url'] : null,
        'deb_sha256' => isset($release['deb_sha256']) && preg_match('/^[a-f0-9]{64}$/i', $release['deb_sha256']) ? strtolower($release['deb_sha256']) : null,
        'sha256' => preg_match('/^[a-f0-9]{64}$/', $sha256) ? $sha256 : null,
        'published_at' => trim((string)($release['published_at'] ?? '')),
        'min_client_version' => trim((string)($release['min_client_version'] ?? SIGNUM_MIN_CLIENT_VERSION)),
    ];
}
function signum_ota_min_client_version(?string $platform = null): ?string
{
    $release = signum_ota_release($platform);
    $minimum = trim((string)($release['min_client_version'] ?? ''));
    return $minimum !== '' ? $minimum : null;
}
function signum_has_ota_update(string $clientVersion, int $clientBuild, ?array $release = null): bool
{
    if ($release === null) {
        return false;
    }
    if ($clientVersion === '') {
        return true;
    }
    if (signum_compare_builds($clientVersion, (string)$release['version']) < 0) {
        return true;
    }
    return $clientBuild < (int)$release['build'];
}
   
                                                                                           
   
function signum_client_is_supported(?string $clientVersion, ?string $platform = null): bool
{
    $minimum = signum_ota_min_client_version($platform);
    if ($minimum === null) {
        return true;
    }
    $version = trim((string)$clientVersion);
    return $version !== '' && signum_compare_builds($version, $minimum) >= 0;
}
   
                                                                             
                                                           
   
function signum_require_min_client(?array $client = null): void
{
    $client = $client ?? signum_client_context();
    $platform = signum_normalize_update_platform((string)($client['platform'] ?? 'windows'));
    $version = (string)($client['vers'] ?? '');
    if (signum_client_is_supported($version, $platform)) {
        return;
    }
    $release = signum_ota_release($platform);
    $minimum = signum_ota_min_client_version($platform);
    signum_json_response([
        'ok' => false,
        'error' => 'client_outdated',
        'message' => 'Эта версия Signum устарела. Обновите приложение до версии ' . $minimum . ' или новее.',
        'min_client_version' => $minimum,
        'latest_version' => $release['version'] ?? null,
        'download_url' => $release['download_url'] ?? null,
        'sha256' => $release['sha256'] ?? null,
        'platform' => $platform,
    ], 426);
}
function signum_auto_purchase_enabled(): bool
{
                                                     
    return true;
}

function signum_auto_purchase_items(?string $clientVersion = null): array
{
    $items = [];
    foreach (signum_active_catalog_apps($clientVersion) as $app) {
        if (array_key_exists('auto_purchase', $app) && empty($app['auto_purchase'])) {
            continue;
        }
        $appId = (string)($app['id'] ?? '');
        if ($appId === '') {
            continue;
        }
        foreach ($app['versions'] ?? [] as $version) {
            if (empty($version['in_store'])) {
                continue;
            }
            if (array_key_exists('auto_purchase', $version) && empty($version['auto_purchase'])) {
                continue;
            }
            $storeId = trim((string)($version['app_store_id'] ?? ''));
            if ($storeId === '' || $storeId === 'NONE' || !ctype_digit($storeId)) {
                continue;
            }
            $bundleId = trim((string)($version['bundle_id'] ?? ''));
            $items[] = [
                'key' => $storeId,
                'app_id' => $appId,
                'app_title' => (string)($app['title'] ?? $appId),
                'title' => (string)($version['title'] ?? $version['label'] ?? ($app['title'] ?? $appId)),
                'version' => (string)($version['version'] ?? ''),
                'bundle_id' => $bundleId !== '' && $bundleId !== 'NONE' ? $bundleId : $storeId,
                'app_store_id' => $storeId,
                'min_ios' => isset($version['min_ios']) ? (string)$version['min_ios'] : null,
                'category' => (string)($app['category'] ?? 'other'),
                'in_store' => true,
            ];
        }
    }

    usort($items, static function (array $a, array $b): int {
        return strcmp((string)$a['app_title'], (string)$b['app_title'])
            ?: strcmp((string)$a['title'], (string)$b['title']);
    });

    return $items;
}

function signum_auto_purchase_fingerprint(array $items): string
{
    $keys = array_values(array_unique(array_map(
        static fn(array $item): string => (string)($item['key'] ?? ''),
        $items
    )));
    sort($keys);
    return hash('sha256', implode(',', $keys));
}

function signum_auto_purchase_payload(?string $clientVersion = null): array
{
    $enabled = signum_auto_purchase_enabled();
    $items = $enabled ? signum_auto_purchase_items($clientVersion) : [];
    return [
        'type' => 'auto_purchase',
        'enabled' => $enabled,
        'count' => count($items),
        'fingerprint' => signum_auto_purchase_fingerprint($items),
        'items' => $items,
        'message' => 'Приложения банков и сервисов из App Store, которые можно купить на Apple ID',
    ];
}
