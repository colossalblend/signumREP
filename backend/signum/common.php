function signum_base_url(): string
{
    $scheme = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
    $host = $_SERVER['HTTP_HOST'] ?? 'localhost';
    $dir = rtrim(str_replace('\\', '/', dirname($_SERVER['SCRIPT_NAME'] ?? '/signum')), '/');
    return $scheme . '://' . $host . $dir;
}

function signum_json_response(array $payload, int $status = 200): void
{
    http_response_code($status);
    header('Content-Type: application/json; charset=utf-8');
    header('Access-Control-Allow-Origin: *');
    header('Access-Control-Allow-Methods: GET, OPTIONS');
    header('Access-Control-Allow-Headers: Content-Type');
    header('Cache-Control: no-store, no-cache, must-revalidate');
    header('X-Signum-Api: ' . SIGNUM_API_VERSION);

    $body = json_encode($payload, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);

    // Catalogue JSON compresses by roughly 85%, and a full scan moves several
    // megabytes of it. Nothing upstream was compressing, so do it here — one
    // place every endpoint already goes through.
    //
    // Opt-in on purpose: clients shipped before this change do not ask for it,
    // and they must keep getting a plain body. Only a request carrying
    // ?type=gzip is compressed, so an old build can never be handed something
    // it cannot read.
    $wantsGzip = strtolower(trim((string)($_GET['type'] ?? ''))) === 'gzip';
    header('Vary: Accept-Encoding');
    if ($wantsGzip
        && $body !== false
        && strlen($body) > 1024
        && function_exists('gzencode')
        && !headers_sent()
        && !ini_get('zlib.output_compression')
    ) {
        $packed = gzencode($body, 6);
        if ($packed !== false && strlen($packed) < strlen($body)) {
            header('Content-Encoding: gzip');
            $body = $packed;
        }
    }

    header('Content-Length: ' . strlen((string)$body));
    echo $body;
    exit;
}

function signum_handle_options(): void
{
    if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'OPTIONS') {
        signum_json_response(['ok' => true]);
    }
}

function signum_normalize_update_platform(?string $value): string
{
    $value = strtolower(trim((string)$value));
    $aliases = [
        'windows' => 'windows',
        'win' => 'windows',
        'desktop' => 'windows',
        'linux' => 'linux',
        'macos' => 'macos',
        'mac' => 'macos',
        'darwin' => 'macos',
        'android' => 'android',
    ];
    return $aliases[$value] ?? 'unknown';
}
function signum_client_context(): array
{
    $requestedPlatform = $_GET['platform'] ?? $_GET['os'] ?? 'windows';
    return [
        'vers' => trim((string)($_GET['vers'] ?? '')),
        'build' => trim((string)($_GET['build'] ?? '')),
        'devkey' => trim((string)($_GET['devkey'] ?? '')),
                                                                               
        'platform' => signum_normalize_update_platform((string)$requestedPlatform),
    ];
}
function signum_compare_builds(string $left, string $right): int
{
    $normalize = static function (string $value): array {
        return array_map('intval', preg_split('/\D+/', $value, -1, PREG_SPLIT_NO_EMPTY) ?: []);
    };
    $a = $normalize($left);
    $b = $normalize($right);
    $len = max(count($a), count($b));
    for ($i = 0; $i < $len; $i++) {
        $av = $a[$i] ?? 0;
        $bv = $b[$i] ?? 0;
        if ($av !== $bv) {
            return $av <=> $bv;
        }
    }
    return 0;
}

function signum_resolve_badge(array $app): string
{
    if (!empty($app['badge'])) {
        return (string)$app['badge'];
    }
    return !empty($app['in_store']) ? 'store' : 'restore';
}

   
                                   
                                                                        
   
