function signum_app_visible_to_client(array $app, string $clientVersion): bool
{
    if (empty($app['active'])) {
        return false;
    }

    // Minimum-version gate. `visible_for_versions` is an exact-match allowlist,
    // which cannot express "this release and everything after it" without
    // listing versions that do not exist yet.
    //
    // A TestFlight entry defaults to 1.1.4 even when the row forgets to say so:
    // older clients have no TestFlight screen, so the card would open the
    // ordinary install flow and fail on an app that was never meant to be
    // downloaded as an IPA.
    $minClient = trim((string)($app['min_client_version'] ?? ''));
    if ($minClient === '' && !empty($app['testflight'])) {
        $minClient = '1.1.4';
    }
    if ($minClient !== '') {
        $clientVersion = trim($clientVersion);
        // An unknown client version is treated as too old: better a missing card
        // than one that opens a flow the build cannot carry out.
        if ($clientVersion === '' || signum_compare_builds($clientVersion, $minClient) < 0) {
            return false;
        }
    }

    $allowedVersions = $app['visible_for_versions'] ?? null;
    if (!is_array($allowedVersions) || $allowedVersions === []) {
        return true;
    }

    $clientVersion = trim($clientVersion);
    if ($clientVersion === '') {
        return false;
    }

    foreach ($allowedVersions as $allowedVersion) {
        if ($clientVersion === trim((string)$allowedVersion)) {
            return true;
        }
    }
    return false;
}

function signum_active_catalog_apps(?string $clientVersion = null): array
{
    $clientVersion = $clientVersion ?? trim((string)($_GET['vers'] ?? ''));
    $apps = array_values(array_filter(
        signum_catalog_apps(),
        static fn(array $app): bool => signum_app_visible_to_client($app, $clientVersion)
    ));

    usort($apps, static function (array $left, array $right): int {
        return ($right['priority'] ?? 0) <=> ($left['priority'] ?? 0);
    });

    return $apps;
}

function signum_app_version(array $app): string
{
    foreach ($app['versions'] ?? [] as $version) {
        if (!empty($version['is_latest']) && !empty($version['version'])) {
            return (string)$version['version'];
        }
    }

    foreach ($app['versions'] ?? [] as $version) {
        if (!empty($version['version'])) {
            return (string)$version['version'];
        }
    }

    return (string)($app['version'] ?? '');
}

